CREATE TABLE IF NOT EXISTS fragcity_cs2_checkout_orders (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_ref CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    steamid64 CHAR(17) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    payload_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    payload_json LONGTEXT NOT NULL,
    payment_method VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    amount_toman BIGINT UNSIGNED NOT NULL,
    amount_rial BIGINT UNSIGNED NOT NULL,
    currency_code VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    authority VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
    ref_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
    status VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'created',
    paymenter_order_id BIGINT UNSIGNED DEFAULT NULL,
    paymenter_invoice_id BIGINT UNSIGNED DEFAULT NULL,
    paymenter_service_id BIGINT UNSIGNED DEFAULT NULL,
    last_error VARCHAR(96) DEFAULT NULL,
    paid_at DATETIME DEFAULT NULL,
    accepted_at DATETIME DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_fragcity_cs2_checkout_order_ref (order_ref),
    UNIQUE KEY uq_fragcity_cs2_checkout_authority (authority),
    UNIQUE KEY uq_fragcity_cs2_checkout_ref_id (ref_id),
    KEY idx_fragcity_cs2_checkout_steam_status (steamid64, status),
    KEY idx_fragcity_cs2_checkout_status_created (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
